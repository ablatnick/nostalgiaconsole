'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('nostalgia', {
  getLibrary: () => ipcRenderer.invoke('library:get'),
  refreshLibrary: () => ipcRenderer.invoke('library:refresh'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  steam: (action, id) => ipcRenderer.invoke('steam:open', action, id),
  stream: (uuid, appId) => ipcRenderer.invoke('moonlight:stream', uuid, appId),
  openMoonlight: () => ipcRenderer.invoke('moonlight:open'),
  refreshMoonlight: () => ipcRenderer.invoke('moonlight:refresh'),
  toggleFullscreen: () => ipcRenderer.invoke('window:fullscreen'),
  quit: () => ipcRenderer.invoke('app:quit'),
  info: () => ipcRenderer.invoke('app:info'),
  onLibrary: (cb) => ipcRenderer.on('library', (_e, lib) => cb(lib)),
  onWelcomeBack: (cb) => ipcRenderer.on('welcome-back', () => cb()),
  onNotice: (cb) => ipcRenderer.on('notice', (_e, n) => cb(n)),
  onWeb: (cb) => ipcRenderer.on('web', (_e, d) => cb(d)),
  keys: () => ipcRenderer.invoke('keys:status'),
  setKeys: (patch) => ipcRenderer.invoke('keys:set', patch),
  web: () => ipcRenderer.invoke('web:get'),
  refreshWeb: () => ipcRenderer.invoke('web:refresh'),
  jfShelves: () => ipcRenderer.invoke('jf:shelves'),
  jfEpisodes: (id) => ipcRenderer.invoke('jf:episodes', id),
  jfReport: (kind, body) => ipcRenderer.invoke('jf:report', kind, body),
  jfOpenWeb: (id) => ipcRenderer.invoke('jf:openWeb', id),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  createProfile: (name) => ipcRenderer.invoke('profile:create', name),
  switchProfile: (id) => ipcRenderer.invoke('profile:switch', id),
  removeProfile: (id) => ipcRenderer.invoke('profile:remove', id),
  soundPack: () => ipcRenderer.invoke('sounds:pack'),
  soundFolder: () => ipcRenderer.invoke('sounds:folder'),
  gamerpics: () => ipcRenderer.invoke('gamerpics:list'),
  gamerpicFolder: () => ipcRenderer.invoke('gamerpics:folder'),
});
